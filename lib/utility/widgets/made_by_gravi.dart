              Image.asset("assets/images/gravi_wordmark.png", height: 15, color: color),
            ],
          ),
        ),
      ),
    );
  }
}

class _GraviCubePainter extends CustomPainter {
  _GraviCubePainter(BuildContext context)
    : body = AppColors.secondaryText.adaptTo(context),
      top = AppColors.secondaryBackground.adaptTo(context),
      side = AppColors.tertiaryBackground.adaptTo(context),
      front = AppColors.background.adaptTo(context),
      background = AppColors.background.adaptTo(context);

  final Color body, top, side, front, background;

  static const _viewBox = Size(970.49, 1000);
  static final _layers = [_bodyPaths, _topPaths, _sidePaths, _frontPaths].map((paths) => paths.map(parseSvgPathData).toList()).toList();

  @override
  void paint(Canvas canvas, Size size) {
    final scale = size.height / _viewBox.height;
    canvas.save();
    canvas.translate((size.width - _viewBox.width * scale) / 2, 0);
    canvas.scale(scale);

    // The body colour is translucent: blended over the page first, so the overlapping body paths don't
    // darken where they meet
    final opaqueBody = Color.alphaBlend(body, background);
    final colors = [opaqueBody, top, side, front];
    for (var i = 0; i < _layers.length; i++) {
      final paint = Paint()
        ..color = colors[i]
        ..isAntiAlias = true;
      for (final path in _layers[i]) {
        canvas.drawPath(path, paint);
      }
    }

    canvas.restore();
  }

  @override
  bool shouldRepaint(_GraviCubePainter old) => old.body != body || old.top != top || old.side != side || old.front != front;
}

